// Netlify build step: turns videos.json (+ the CF_STREAM_CUSTOMER_CODE environment variable)
// into site/videos.config.js, and stops the deploy if any portfolio video would have no HD source.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cfg = JSON.parse(readFileSync(join(root, "videos.json"), "utf8"));
const code = (process.env.CF_STREAM_CUSTOMER_CODE || cfg.customerCode || "").trim();
const allowMissing = /^(1|true|yes)$/i.test(process.env.ALLOW_MISSING_STREAM_IDS || "");
const okId = id => /^[0-9a-f]{32}$/i.test(String(id || ""));

const problems = [];
if (!/^[0-9a-z]{6,}$/i.test(code)) problems.push("Cloudflare customer code is missing (set CF_STREAM_CUSTOMER_CODE in Netlify, or customerCode in videos.json).");
const missing = Object.entries(cfg.videos).filter(([, v]) => v.onSite && !v.local && !okId(v.streamId));
const bad = Object.entries(cfg.videos).filter(([, v]) => v.streamId && !okId(v.streamId));
bad.forEach(([k, v]) => problems.push(`${k}: "${v.streamId}" is not a Cloudflare video ID (32 letters/numbers).`));
if (missing.length) problems.push(`${missing.length} portfolio videos have no Cloudflare video ID yet: ${missing.map(([k]) => k).join(", ")}`);

const out = {
  customerCode: code,
  manifestUrl: cfg.manifestUrl || undefined,
  hlsScript: cfg.hlsScript || undefined,
  fallbackBase: cfg.fallbackBase || "",
  videos: Object.fromEntries(Object.entries(cfg.videos).map(([k, v]) => [k, { file: v.file, streamId: okId(v.streamId) ? v.streamId : "", local: !!v.local }]))
};
writeFileSync(join(root, "site", "videos.config.js"),
  "/* Generated by scripts/build-config.mjs from videos.json. Edit videos.json, not this file. */\n" +
  "window.MG_VIDEO_CONFIG = " + JSON.stringify(out, null, 1) + ";\n");


// Security headers: a Content-Security-Policy that only lets this site's own scripts run (inline ones by hash),
// plus HSTS and the usual hardening headers. Written to site/_headers on every build so the hashes always match.
import { createHash } from "node:crypto";
{
  const html = readFileSync(join(root, "site", "index.html"), "utf8");
  const hashes = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m => `'sha256-${createHash("sha256").update(m[1], "utf8").digest("base64")}'`);
  const cf = "https://*.cloudflarestream.com https://videodelivery.net";
  const csp = [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(" ")} blob: https://connect.facebook.net`,
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
    "font-src 'self' https://fonts.gstatic.com",
    `img-src 'self' data: blob: ${cf} https://www.facebook.com`,
    `media-src 'self' blob: ${cf}`,
    `connect-src 'self' ${cf} https://www.facebook.com https://connect.facebook.net`,
    "worker-src 'self' blob:",
    "manifest-src 'self'",
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "object-src 'none'",
    "upgrade-insecure-requests"
  ].join("; ");
  const headers = [
    "/*",
    `  Content-Security-Policy: ${csp}`,
    "  Strict-Transport-Security: max-age=31536000; includeSubDomains",
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: strict-origin-when-cross-origin",
    "  X-Frame-Options: DENY",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()",
    "  Cross-Origin-Opener-Policy: same-origin",
    ""
  ].join("\n");
  writeFileSync(join(root, "site", "_headers"), headers);
  console.log(`Security headers written (${hashes.length} inline script hash${hashes.length === 1 ? "" : "es"}).`);
}

const need = Object.values(cfg.videos).filter(v => v.onSite && !v.local);
const ready = need.filter(v => okId(v.streamId)).length;
const local = Object.values(cfg.videos).filter(v => v.onSite && v.local).length;
console.log(`Cloudflare Stream: ${ready}/${need.length} popup videos linked; ${local} banner/slider videos play from the site.`);
if (problems.length) {
  problems.forEach(p => console.error("  - " + p));
  if (!allowMissing) { console.error("Deploy stopped so no visitor sees a video without its HD version. Add the IDs (see README) and push again."); process.exit(1); }
  console.warn("ALLOW_MISSING_STREAM_IDS is on: videos without an ID play their preview loop in the popup.");
}
